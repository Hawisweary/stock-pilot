def classify_etf(name: str | None) -> str:
    """按名称归一级分类。无法归类→'其他'。"""
    if not name:
        return "其他"
    n = re.sub(r"ETF.*$", "", str(name))  # 去掉 "ETF"/"ETF联接" 等后缀干扰
    for category, kws in _RULES:
        for kw in kws:
            if kw in name or kw in n:
                return category
    return "其他"
